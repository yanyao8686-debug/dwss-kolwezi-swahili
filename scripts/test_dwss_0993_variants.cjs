'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('index.html'),app=read('app.js'),shared=read('shared-lexicon.js'),sw=read('sw.js'),version=read('VERSION.txt');
assert.match(version,/^Version: 0\.9\.93$/m);
assert.match(html,/DWSS_AUTO_UPDATE_0_9_93/);
assert.match(html,/content="0\.9\.93"/);
assert.match(html,/id="resultReading"/);
assert.match(html,/id="translationPronunciationCandidates"/);
assert.match(html,/id="translationPronunciationCandidateList"/);
assert.match(html,/>提交读音候选<\/button>/);
assert.doesNotMatch(html,/<div class="translation-correction-help">/);
assert.match(app,/function renderTranslationPronunciationCandidates\(/);
assert.match(app,/status==='common'\?0:status==='confirmed'\?1:status==='pending'\?2/);
assert.match(app,/source_kind:'translation'/);
assert.match(app,/toSyllables\(reading,true\)\.join\(' '\)/);
assert.match(app,/submitPronunciationVariant/);
assert.match(app,/相同拼音的读音已存在/);
assert.match(app,/原始读音未被覆盖/);
const submit=app.slice(app.indexOf('async function submitTranslationCorrection(){'),app.indexOf('async function restoreTranslationCorrection(){'));
assert.doesNotMatch(submit,/updateTranslation/,'main correction must add a candidate, not replace a single shared row');
assert.match(shared,/const sourceKind = String\(input && input\.source_kind \|\| "dictionary"\)/);
assert.match(shared,/isTranslation \? 2000 : 100/);
assert.match(shared,/isTranslation \? 16000 : 400/);
assert.match(shared,/source_kind: sourceKind/);
assert.match(shared,/mergePronunciationVariant\(result\.data\.variant\)/);
assert.match(shared,/postgres_changes/);
assert.match(sw,/APP_VERSION = '0\.9\.93'/);
const precache=sw.match(/const PRECACHE_URLS = \[([\s\S]*?)\];/);
assert.ok(precache);
assert.match(precache[1],/shared-lexicon\.js/);
assert.match(precache[1],/app\.js/);
assert.doesNotMatch(precache[1],/\.apk/i);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
const duplicate=ids.filter((x,i)=>ids.indexOf(x)!==i);
assert.deepEqual([...new Set(duplicate)],[],'no duplicate DOM ids');
assert.match(html,/id="dwss-apk-download"/);
assert.match(html,/href="\.\/DWSS-Android-0\.9\.80\.apk"/);
console.log('PASS DWSS 0.9.93 shared multi-pronunciation candidates, pinyin dedupe, phrase-length validation, realtime and compact UI.');
