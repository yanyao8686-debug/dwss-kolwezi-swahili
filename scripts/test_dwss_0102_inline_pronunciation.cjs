'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('index.html'),app=read('app.js'),shared=read('shared-lexicon.js'),controls=read('dwss-pronunciation-controls.js'),boot=read('boot.js'),sw=read('sw.js'),version=read('VERSION.txt');
const liveVersion=(version.match(/^Version: ([0-9.]+)$/m)||[])[1];
assert.ok(['0.9.102','0.9.103'].includes(liveVersion),'unexpected app version: '+liveVersion);
const versionToken=liveVersion.replace(/\./g,'_');
assert.ok(html.includes('DWSS_AUTO_UPDATE_'+versionToken));
assert.ok(html.includes('content="'+liveVersion+'"'));
assert.match(html,/id="resultReading"/);
assert.match(html,/id="submitTranslationCorrection"/);
assert.match(html,/id="translationPronunciationCandidateList"/);
assert.match(html,/点击旁边的读音即可载入上方输入框/);
assert.match(controls,/保存并同步/);
assert.doesNotMatch(controls,/管理读音|历史记录|showModal|createElement\('dialog'\)/);
for(const id of ['submitTranslationVariant','restoreTranslationCorrection','viewTranslationCorrectionHistory','viewWithdrawnVariants']) {
  assert.ok(controls.includes("'"+id+"'"), 'hidden legacy entry must be retained: '+id);
}
assert.match(app,/function dwssPinyinKeysNear/);
assert.match(app,/pronunciation_aliases:Array\.isArray\(v\.pronunciation_aliases\)/);
assert.match(app,/const sourceKind=state\.sourceKind==='dictionary'\?'dictionary':'translation'/);
assert.match(app,/dictionaryApi\.update\(payload\)/);
assert.match(app,/dictionaryApi\.updateTranslation\(payload\)/);
assert.match(app,/variantApi\.managePronunciationVariant/);
assert.match(app,/submitVariant\(previous\)/);
assert.match(app,/submitVariant\(reading\)/);
assert.match(app,/REVISION_CONFLICT/);
assert.match(shared,/pronunciation_aliases\.some\(alias/);
assert.doesNotMatch(shared,/v\.pinyin_key && v\.pinyin_key === pinyinKey/,'local cache must not suppress same-sound alias submissions before server merge');
assert.match(shared,/data\.retired_variant_id/);
assert.match(boot,/dwss-pronunciation-controls\.js/);
assert.match(sw,/APP_VERSION = '0\.9\.102'/);
assert.match(sw,/['"]\.\/dwss-pronunciation-controls\.js['"]/);
const precache=(sw.match(/const PRECACHE_URLS = \[(.*?)\];/s)||[])[1]||'';
assert.ok(precache.includes("'./dwss-pronunciation-controls.js'"));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.deepEqual([...new Set(ids.filter((id,i)=>ids.indexOf(id)!==i))],[],'HTML IDs must remain unique');
const helperStart=app.indexOf('function dwssPinyinSyllableNear');
const helperEnd=app.indexOf('\nfunction renderTranslationPronunciationCandidates',helperStart);
assert.ok(helperStart>=0&&helperEnd>helperStart,'sound helper functions must exist');
const sandbox={window:{DWSSPronunciationSearch:{toSyllables:()=>[]}}};
vm.runInNewContext(app.slice(helperStart,helperEnd),sandbox);
assert.equal(sandbox.dwssPinyinKeysNear('feng gu la','feng gu na'),true,'selected near-sound pair should merge');
assert.equal(sandbox.dwssPinyinKeysNear('feng gu la','feng gu lu'),false,'distinct sound should remain parallel');
assert.equal(sandbox.dwssPinyinKeysNear('ma qiu','ma qiu'),false,'exact match is handled separately from near match');
const crypto=require('node:crypto');
const apk=fs.readFileSync(path.join(root,'DWSS-Android-Installer.apk'));
assert.equal(crypto.createHash('sha256').update(apk).digest('hex'),'9df93884f7eafe9e3cf8ba77d61c61e7a1b050360be691d1a39e6999e3fa37f5','stable Android WebView shell must be unchanged');
console.log('PASS DWSS '+liveVersion+': inline save, unified word/phrase routing, editable grouped variants, near-sound matching, offline cache, and unchanged Android APK.');
