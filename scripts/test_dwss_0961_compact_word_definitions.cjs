'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const root = process.env.DWSS_TEST_ROOT || 'public';
const read = name => fs.readFileSync(root + '/' + name, 'utf8');
const html = read('index.html'), app = read('app.js'), sw = read('sw.js'), version = read('VERSION.txt');

assert(html.includes('content="0.9.61"><!-- DWSS_AUTO_UPDATE_0_9_61 -->'));
assert(html.includes('版本 0.9.61 · DWSS 智能翻译 PWA'));
assert(sw.includes("const APP_VERSION = '0.9.61';"));
assert(version.includes('Version: 0.9.61'));
assert(html.includes('单个斯语读法释义：</div>'));
assert(!html.includes('单个斯语读法释义（点击加号展开）'));
assert(!html.includes("document.createElement('details');disclosure.className='dwss-secondary-details'"));
assert(html.includes("document.createElement('section');section.className='dwss-secondary-details'"));
assert(html.includes("node.textContent.includes('单个斯语读法释义')"));
assert(html.includes('.dwss-secondary-title{display:block!important;'));
assert(html.includes('grid-template-columns:minmax(42px,30%) minmax(0,1fr)!important'));
assert(html.includes('padding:5px 2px!important'));
assert(html.includes('.dwss-secondary-details .segment-meta{display:none!important}'));
assert(app.includes("version:'0.9.61'"));
assert(app.includes('<details class="segment-meta">'));
assert(html.includes('#resultCard .dwss-secondary-details .segment-meta{display:none!important}'));
const sectionStart = html.indexOf("    const secondary=[];");
const sectionEnd = html.indexOf("    const goTranslate=()=>", sectionStart);
assert(sectionStart >= 0 && sectionEnd > sectionStart);
const sectionScript = html.slice(sectionStart, sectionEnd);
assert(sectionScript.includes("document.createElement('section')"));
assert(!sectionScript.includes("document.createElement('details')"));
assert(sectionScript.includes("node.textContent='单个斯语读法释义：'"));
assert(sectionScript.includes("node.className='dwss-secondary-title'"));
assert(sectionScript.includes("section.appendChild(node)"));
const css = html.slice(html.indexOf('#resultCard .dwss-secondary-details{'), html.indexOf('#samples[hidden]'));
assert(css.includes('display:flex!important;flex-direction:column!important'));
assert(css.includes('border:0!important;border-bottom:1px solid'));
assert(css.includes('.seg .src{display:none!important}'));
assert(css.includes('.candidate-extra{display:none!important}'));
console.log('PASS: heading is fixed text, not a disclosure summary.');
console.log('PASS: stats, quality notes and the word list are mounted in a visible section.');
console.log('PASS: word translations use compact borderless rows, not oversized cards.');
console.log('PASS: nested per-word details are visually removed to save space.');
