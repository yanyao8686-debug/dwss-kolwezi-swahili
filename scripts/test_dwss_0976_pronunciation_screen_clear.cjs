#!/usr/bin/env node
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const html=read('index.html'),app=read('app.js'),sw=read('sw.js'),boot=read('boot.js');
const version=read('VERSION.txt'),manifest=JSON.parse(read('manifest.webmanifest'));
assert.match(version,/^Version: 0\.9\.76$/m);
assert(sw.includes("const APP_VERSION = '0.9.76';"));
assert(html.includes('content="0.9.76">'));
assert(html.includes('DWSS_AUTO_UPDATE_0_9_76'));
assert(html.includes('版本 0.9.76 · 刚果金斯语翻译'));
assert(html.includes('data-tab="pronunciation"'));
assert(html.includes('<input id="pronunciationSearch"'));
assert(html.includes('<div id="pronunciationResults" aria-live="polite"></div>'));
assert(!html.includes('pronunciation-lookup-hint'));
assert(!html.includes('pronunciation-lookup-summary'));
assert(!html.includes('支持同音字与近似读音'));
assert(!html.includes('输入谐音后立即查询'));
assert(!html.includes('输入你记得的中文谐音，系统会立即搜索词库中的对应斯语词条'));
assert(!app.includes("id=\\'pronunciationCount\\'"));
assert(app.includes("const host=$('pronunciationResults'),input=$('pronunciationSearch');"));
assert(app.includes("if(!query){host.innerHTML='';return;}"));
assert(app.includes("pronunciationInput.value='';renderPronunciationLookup();"));
assert(app.includes("function clearAllInputs()"));
assert(app.includes("clearEntryForm();"));
assert(app.includes("renderTranslation({recordHistory:false});"));
assert(app.includes("const entries=all.map(item=>({zh:item.zh"));
assert(boot.indexOf('./hanzi-pinyin.js')<boot.indexOf('./pronunciation-search.js'));
assert(boot.indexOf('./pronunciation-search.js')<boot.indexOf('./app.js'));
assert(sw.includes('./hanzi-pinyin.js')&&sw.includes('./pronunciation-search.js'));
assert.equal(manifest.id,'./?app=dwss-kolwezi-swahili');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.name,'刚果金斯语翻译');
console.log('PASS: red-box explanatory text, support hint, status chip and blank-state copy removed.');
console.log('PASS: pronunciation query input is the first control below its heading.');
console.log('PASS: Clear All clears pronunciation input and empties its results.');
console.log('PASS: full lexicon homophone search and offline module loading are retained.');
