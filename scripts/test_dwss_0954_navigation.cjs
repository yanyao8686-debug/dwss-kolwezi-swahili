'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const root = process.env.DWSS_TEST_ROOT || 'public';
const read = name => fs.readFileSync(root + '/' + name, 'utf8');
const html = read('index.html');
const app = read('app.js');
const boot = read('boot.js');
const sw = read('sw.js');
const pwa = read('pwa.js');
const overrides = read('dictionary-overrides.js');
const shared = read('shared-lexicon.js');
const version = read('VERSION.txt');

const nav = html.match(/<nav class="tabs">([\s\S]*?)<\/nav>/);
assert(nav, 'main navigation exists');
assert.equal((nav[1].match(/<button\b/g) || []).length, 3, 'main navigation has exactly three actions');
assert(nav[1].includes('data-tab="maintenance"'), 'Add New Word main action remains');
assert(nav[1].includes('data-tab="saved"'), 'History main action remains');
assert(nav[1].includes('nav-clear-slot'), 'Clear main action remains');
assert(!nav[1].includes('data-tab="dictionary"'), 'no standalone dictionary tab');
assert(!nav[1].includes('词库'), 'no dictionary label in main navigation');
assert(html.includes('grid-template-columns:repeat(3,minmax(0,1fr))'), 'three-column layout restored');
assert(!html.includes('grid-template-columns:repeat(4,minmax(0,1fr))'), 'no four-column navigation residue');

assert(html.includes('id="openPublicPronunciationEditor"'), 'public editor has an entry under Add New Word');
assert(html.includes('id="maintenance"'), 'Add New Word panel remains');
assert(html.includes('id="dictionary"'), 'internal dictionary/editor panel remains');
assert(html.includes('id="dictSearch"'), 'dictionary search remains');
assert(html.includes('id="publicPronunciationList"'), 'public corrections list remains');
assert(html.includes('id="pronunciationEditor"'), 'pronunciation editor dialog remains');
assert(html.includes('id="restoreBuiltinPronunciation"'), 'restore built-in reading remains');
assert(app.includes("switchTab('dictionary')"), 'secondary action opens internal dictionary editor');
assert(html.includes("['maintenance','saved','dictionary'].forEach(panelId=>{"), 'dictionary panel has a return-to-translation control');
assert(html.includes("back.textContent='← 返回翻译主界面'"), 'return-to-translation text remains');
assert.match(html, /\.dwss-return-translation\{[^}]*color:#ff4b12!important;[^}]*font-size:16px!important;[^}]*text-decoration-line:underline!important;/);
assert.match(html, /DWSS_AUTO_UPDATE_0_9_54/);
assert.match(html, /版本 0\.9\.54 · DWSS/);
assert(app.includes("version:'0.9.54'"));
assert(sw.includes("const APP_VERSION = '0.9.54';"));
assert(pwa.includes('registration.update()'), 'automatic update check remains');
assert(pwa.includes('DWSS_SKIP_WAITING'), 'automatic activation remains');
assert(boot.includes("'./dictionary-overrides.js'"), 'dictionary public edits module remains loaded');
assert(overrides.includes('dwss-edit-dictionary-pronunciation'), 'server-validated public edit function remains');
assert(!overrides.includes('SUPABASE_SERVICE_ROLE_KEY'), 'no server secret appears in frontend module');
assert(shared.includes('dwss_shared_terms_queue_v1'), 'offline queue remains');
assert(shared.includes('dwss:personal-term-added'), 'new-word event remains');
assert(shared.includes('addEventListener("online", connectCloud)'), 'online auto-sync trigger remains');
assert(shared.includes('client_submit_id'), 'idempotency key remains');
assert(shared.includes('await flushQueue(client)'), 'queue flush on reconnect remains');
assert(html.includes('id="newFrenchReadingZh"'), 'French homophone input remains on Add New Word page');
assert(!html.includes('id="resultFrenchReading"'), 'no separate French output panel on translation home');
assert(version.includes('Version: 0.9.54'));
console.log('PASS: DWSS 0.9.54 navigation, editor reachability, return-link style, offline queue, and auto-update safeguards.');
