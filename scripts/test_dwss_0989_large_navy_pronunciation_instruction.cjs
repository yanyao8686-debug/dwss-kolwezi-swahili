#!/usr/bin/env node
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=process.env.DWSS_PUBLIC_DIR||'public',read=n=>fs.readFileSync(path.join(root,n),'utf8');
const html=read('index.html'),app=read('app.js'),boot=read('boot.js'),pwa=read('pwa.js'),sw=read('sw.js'),version=read('VERSION.txt'),manifest=JSON.parse(read('manifest.webmanifest'));
const sentence='输入听到却不懂意思的斯语中文谐音时，即便是同音不同字的中文，系统也会自动查询近似的读音来匹配对应发音的斯语';
assert.match(version,/^Version: 0\.9\.89$/m);
assert(sw.includes("const APP_VERSION = '0.9.89';"));
assert(html.includes('content="0.9.89">')&&html.includes('DWSS_AUTO_UPDATE_0_9_89'));
assert(html.includes('版本 0.9.89 · 刚果金斯语翻译'));
assert((html.match(/dwss-release=0\.9\.89/g)||[]).length>=3);
assert(!html.includes('dwss-release=0.9.88'));
assert(app.includes("version:'0.9.89'"));
assert.equal(html.split(sentence).length-1,1);
assert(!html.includes('dwss-pronunciation-instruction-frame-0988'));
const m=html.match(/<style id="dwss-pronunciation-instruction-style-0989">([\s\S]*?)<\/style>/);
assert(m,'large navy instruction style exists');
const css=m[1];
for(const declaration of ['color:#173b78!important','font-size:clamp(18px,5vw,38px)!important','font-weight:700!important','text-align:center!important','border:none!important','border-width:0!important','outline:none!important','border-radius:0!important','box-shadow:none!important','background:transparent!important','white-space:normal!important','overflow-wrap:anywhere!important','word-break:normal!important'])assert(css.includes(declaration),'missing CSS: '+declaration);
assert(html.indexOf('<input id="pronunciationSearch"')<html.indexOf('<div class="pronunciation-lookup-instruction" role="note">'));
assert(pwa.includes('const UPDATE_COUNTDOWN_SECONDS = 5;'));
assert(pwa.includes("setState('更新倒计时 ' + remaining, 'pwa-state-warn'"));
assert(pwa.includes("setState('自动更新完毕', 'pwa-state-ok'"));
assert(pwa.includes("setState('自动更新已开启', 'pwa-state-ok'"));
assert(html.includes("timeZone:'Africa/Lubumbashi'")&&html.includes('dwss-announcement-controller'));
assert.equal(manifest.id,'./?app=dwss-kolwezi-swahili');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.name,'刚果金斯语翻译');
assert(boot.indexOf('./hanzi-pinyin.js')<boot.indexOf('./pronunciation-search.js'));
assert(boot.indexOf('./pronunciation-search.js')<boot.indexOf('./app.js'));
console.log('PASS: exact instruction, large responsive navy typography and no frame.');
console.log('PASS: input order, update countdown, Lubumbashi daily announcement, vocabulary and PWA identity.');
