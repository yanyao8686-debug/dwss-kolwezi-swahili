#!/usr/bin/env node
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const html=read('index.html'),app=read('app.js'),sw=read('sw.js'),boot=read('boot.js');
const version=read('VERSION.txt'),manifest=JSON.parse(read('manifest.webmanifest'));
const instruction='输入听到却不懂意思的斯语中文谐音时，不限同音不同字的中文，系统会自动查询近似的读音来匹配对应发音的斯语';
assert.match(version,/^Version: 0\.9\.77$/m);
assert(sw.includes("const APP_VERSION = '0.9.77';"));
assert(html.includes('content="0.9.77">'));
assert(html.includes('DWSS_AUTO_UPDATE_0_9_77'));
assert(html.includes('版本 0.9.77 · 刚果金斯语翻译'));
assert.equal((html.match(new RegExp(instruction,'g'))||[]).length,1);
assert(html.includes('<div class="pronunciation-lookup-instruction" role="note">'+instruction+'</div>'));
assert(!html.includes('<h2>发音查询</h2>'));
const style=html.match(/<style id="dwss-pronunciation-instruction-frame-0977">([\s\S]*?)<\/style>/);
assert(style,'framed instruction CSS exists');
assert(style[1].includes('border:1.5px solid #111'));
assert(style[1].includes('border-radius:0'));
assert(style[1].includes('white-space:normal'));
assert(html.includes('<input id="pronunciationSearch"'));
assert(html.includes('<div id="pronunciationResults" aria-live="polite"></div>'));
assert(!html.includes('pronunciation-lookup-hint'));
assert(!html.includes('pronunciation-lookup-summary'));
assert(app.includes("version:'0.9.77'"));
assert(app.includes("pronunciationInput.value='';renderPronunciationLookup();"));
assert(app.includes('function renderPronunciationLookup()'));
assert(app.includes("const entries=all.map(item=>({zh:item.zh"));
assert(boot.indexOf('./hanzi-pinyin.js')<boot.indexOf('./pronunciation-search.js'));
assert(boot.indexOf('./pronunciation-search.js')<boot.indexOf('./app.js'));
assert(sw.includes('./hanzi-pinyin.js')&&sw.includes('./pronunciation-search.js'));
assert.equal(manifest.id,'./?app=dwss-kolwezi-swahili');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.name,'刚果金斯语翻译');
console.log('PASS: exact requested explanation appears once under the pronunciation tab.');
console.log('PASS: explanatory text is enclosed by a solid black rectangular border.');
console.log('PASS: query input, fuzzy pronunciation lookup and Clear All behavior remain intact.');
console.log('PASS: offline pinyin/search modules and PWA identity are preserved.');
