const assert=require('node:assert/strict');
const fs=require('node:fs');
const zlib=require('node:zlib');
const path=require('node:path');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('index.html');
const app=read('app.js');
const boot=read('boot.js');
const sw=read('sw.js');
const version=read('VERSION.txt');
const manifest=JSON.parse(read('manifest.webmanifest'));
const gzip=fs.readFileSync(path.join(root,'dictionary.js.gz'));
const source=zlib.gunzipSync(gzip).toString('utf8');
const match=source.match(/^window\.SW_DB\s*=\s*(\[.*\]);\s*$/s);
assert(match,'compressed dictionary exports SW_DB JSON');
const dictionary=JSON.parse(match[1]);
assert(dictionary.length>=2042,'the original large dictionary remains present');
assert(version.includes('Version: 0.9.70'),'published version file is 0.9.70');
assert(sw.includes("const APP_VERSION = '0.9.70';"),'Service Worker cache version is 0.9.70');
assert(boot.includes("|| '0.9.70';"),'bootstrap fallback version is current');
assert(app.includes("name:'刚果金斯语翻译',owner:'德威安全官陈谍',version:'0.9.70'"),'application metadata is current');
assert(html.includes('content="0.9.70">'),'HTML automatic update metadata is current');
assert(html.includes('dwss-release=0.9.70'),'entry scripts bypass stale versioned resources');
assert(html.includes('版本 0.9.70 · 刚果金斯语翻译'),'footer version is current');
const footer='<div class="footer">版本 0.9.70 · 刚果金斯语翻译<span class="ownership-stamp">© 2026 刚果金斯语翻译/ 该应用由德威安全官陈谍匠心开发 · 保留所有权利</span></div>';
assert(html.includes(footer),'footer text exactly matches the requested website wording');
assert(html.includes('dwss:announcement-dismissed:0.9.70:'),'announcement has release-specific persistent dismissal');
assert(html.includes("get('dwss-native-app')==='1'"),'native Android gets a separate announcement state');
assert(html.includes('我已阅读，进入应用'),'announcement has its close action');
assert.equal(manifest.id,'./?app=dwss-kolwezi-swahili','PWA install identity is preserved');
assert.equal(manifest.display,'standalone','PWA standalone mode is preserved');
assert.equal(manifest.name,'刚果金斯语翻译','PWA product name is preserved');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
const duplicates=ids.filter((id,i)=>ids.indexOf(id)!==i);
assert.deepEqual([...new Set(duplicates)],[],'HTML IDs stay unique');
console.log('PASS: 0.9.70 footer exactly matches expected ownership statement.');
console.log('PASS: Android announcement is independent from browser dismissal state.');
console.log('PASS: Service Worker, metadata, versioned scripts and PWA identity verified.');
console.log('PASS: dictionary retained ('+dictionary.length+' source entries).');
