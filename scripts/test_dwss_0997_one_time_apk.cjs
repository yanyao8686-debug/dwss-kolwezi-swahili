'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const assert=require('node:assert/strict');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('index.html'),app=read('app.js'),pwa=read('pwa.js'),sw=read('sw.js'),version=read('VERSION.txt');
assert.match(version,/^Version: 0\.9\.97$/m);
assert.match(html,/DWSS_AUTO_UPDATE_0_9_97/);
assert.match(html,/content="0\.9\.97"/);
assert.match(html,/当前软件版本 <span id="apkWebVersion">0\.9\.97<\/span>/);
assert.match(html,/href="\.\/DWSS-Android-Installer\.apk"/);
assert.match(html,/download="刚果金斯语翻译-首次安装包\.apk"/);
assert.match(html,/首次安装一次即可；联网后软件自动更新，无需重新下载 APK/);
assert.doesNotMatch(html,/版本 0\.9\.80/);
assert.doesNotMatch(html,/DWSS-Android-0\.9\.80\.apk/);
assert.match(app,/version:'0\.9\.97'/);
assert.match(pwa,/VERSION\.txt\?dwss-version-check=/);
assert.match(pwa,/const installerVersion = \$\('apkWebVersion'\)/);
assert.match(pwa,/installerVersion\.textContent = match\[1\]/);
assert.match(pwa,/textNode\.nodeValue = '版本 ' \+ match\[1\]/);
assert.match(sw,/APP_VERSION = '0\.9\.97'/);
assert.match(sw,/endsWith\('\.apk'\)/);
const oldApk=fs.readFileSync(path.join(root,'DWSS-Android-0.9.80.apk'));
const stableApk=fs.readFileSync(path.join(root,'DWSS-Android-Installer.apk'));
assert.equal(stableApk.length,5806530);
assert.equal(crypto.createHash('sha256').update(stableApk).digest('hex'),'9df93884f7eafe9e3cf8ba77d61c61e7a1b050360be691d1a39e6999e3fa37f5');
assert.deepEqual(stableApk,oldApk,'stable URL must serve the exact same approved APK, not an unverified rebuild');
const manifest=JSON.parse(read('manifest.webmanifest'));
assert.equal(manifest.name,'刚果金斯语翻译');
const precache=sw.match(/const PRECACHE_URLS = \[([\s\S]*?)\];/);
assert.ok(precache);
assert.doesNotMatch(precache[1],/\.apk/i);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
const duplicates=ids.filter((id,i)=>ids.indexOf(id)!==i);
assert.deepEqual([...new Set(duplicates)],[],'no duplicate HTML IDs');
console.log('PASS DWSS 0.9.97: stable installer exact bytes, live web version in APK panel, auto-update version source, and unique IDs.');
