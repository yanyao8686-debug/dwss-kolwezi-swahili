'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('index.html'),app=read('app.js'),shared=read('shared-lexicon.js'),sw=read('sw.js'),version=read('VERSION.txt');
assert.match(version,/^Version: 0\.9\.108$/m);
assert.match(html,/DWSS_AUTO_UPDATE_0_9_108/);
assert.match(html,/content="0\.9\.108"/);
assert.match(app,/version:'0\.9\.108'/);
assert.match(sw,/APP_VERSION = '0\.9\.108'/);
for(const id of ['inputText','resultReading','submitTranslationCorrection','translationPronunciationCandidates','translationPronunciationCandidateList']) assert.ok(html.includes('id="'+id+'"'),'missing '+id);
for(const old of ['missingWordActions','missingWordActionList','添加此词','当前输入中有未收录内容']) assert.ok(!html.includes(old),'obsolete missing-word UI remains: '+old);
assert.match(app,/isStandaloneUnknown/);
assert.match(app,/submitQuickTranslationTerm/);
assert.match(app,/置顶/);
assert.match(app,/data-dwss-pin/);
assert.match(app,/await submitTranslationCorrection\(\)/);
assert.match(app,/DWSSSharedLexicon/);
assert.match(shared,/async function submitQuickTranslationTerm/);
assert.match(shared,/__quick_translation_term/);
assert.match(shared,/pinQuickTranslationPrimary/);
assert.match(shared,/dwss-edit-dictionary-pronunciation/);
assert.match(shared,/__quick_pinyin_key/);
assert.match(shared,/dwss-submit-pronunciation-variant/);
assert.match(shared,/submitQuickTranslationTerm,/);
assert.match(html,/id="translationCorrectionPanel"/);
assert.match(html,/id="translationActionNotice"/);
assert.match(html,/flex-direction:column/);
assert.doesNotMatch(html,/scroll-snap-type:x/,'candidate rail should no longer be a wide horizontal carousel');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.deepEqual([...new Set(ids.filter((id,i)=>ids.indexOf(id)!==i))],[],'HTML IDs must be unique');
for(const file of ['app.js','shared-lexicon.js','sw.js','boot.js','dwss-pronunciation-controls.js','dictionary-overrides.js']){
  const cp=require('node:child_process').spawnSync(process.execPath,['--check',path.join(root,file)],{encoding:'utf8'});
  assert.equal(cp.status,0,file+' syntax error: '+(cp.stderr||cp.stdout));
}
const crypto=require('node:crypto');
const apk=fs.readFileSync(path.join(root,'DWSS-Android-Installer.apk'));
assert.equal(crypto.createHash('sha256').update(apk).digest('hex'),'9df93884f7eafe9e3cf8ba77d61c61e7a1b050360be691d1a39e6999e3fa37f5','Android installer must remain byte-identical');
console.log('PASS DWSS 0.9.108: single main editor; direct shared add for unknown single words; compact candidate list; global pin action; unique HTML IDs; JS syntax; unchanged APK.');
