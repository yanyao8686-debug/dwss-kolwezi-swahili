'use strict';
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('index.html'),app=read('app.js'),shared=read('shared-lexicon.js'),over=read('dictionary-overrides.js'),sw=read('sw.js'),pwa=read('pwa.js'),version=read('VERSION.txt');
assert.match(version,/^Version: 0\.9\.100$/m);
assert.match(html,/DWSS_AUTO_UPDATE_0_9_100/);
assert.match(html,/content="0\.9\.100"/);
assert.doesNotMatch(html,/<div class="footer">/);
assert.match(html,/id="resultReading"/);
assert.match(html,/id="submitTranslationCorrection"/);
assert.match(html,/id="viewTranslationCorrectionHistory"/);
assert.match(html,/id="viewWithdrawnVariants"/);
assert.match(html,/id="sharedVariantEditorDialog"/);
assert.match(html,/id="sharedVariantHistoryDialog"/);
assert.match(html,/id="translationOverrideHistoryDialog"/);
assert.match(html,/translation-pronunciation-candidate-rail/);
assert.match(html,/overflow-x:auto/);
assert.match(html,/id="dwss-apk-download"/);
assert.match(html,/href="\.\/DWSS-Android-Installer\.apk"/);
assert.match(html,/id="apkWebVersion"/);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const duplicates=ids.filter((id,i)=>ids.indexOf(id)!==i);
assert.deepEqual([...new Set(duplicates)],[],'HTML IDs must be unique');
const correction=app.slice(app.indexOf('async function submitTranslationCorrection(){'),app.indexOf('\nasync function submitTranslationPronunciationVariant(){'));
assert.match(correction,/DWSSDictionaryOverrides\.updateTranslation/);
assert.doesNotMatch(correction,/submitPronunciationVariant/,'main correction must update its current override, not append a new candidate');
assert.match(correction,/window\.confirm/,'a final confirmation is required before syncing');
assert.match(app,/submitTranslationVariant/,'the separate add-variant action must remain available');
assert.match(app,/const displayReading=legacyReading\|\|\(preferredCommunity\?/,'current correction must take precedence over old candidate submissions');
assert.match(app,/openWithdrawnSharedVariants/);
assert.match(app,/restoreSharedVariantHistory/);
assert.match(app,/restoreTranslationOverrideHistory/);
assert.match(shared,/dwss-manage-pronunciation-variant/);
assert.match(shared,/managePronunciationVariant/);
assert.match(over,/dwss-manage-pronunciation-override/);
assert.match(over,/historyTranslation/);
assert.match(over,/restoreTranslationHistory/);
assert.match(pwa,/installerVersion\.textContent = match\[1\]/);
assert.match(pwa,/if \(footer\) \{/);
assert.match(sw,/APP_VERSION = '0\.9\.100'/);
const precache=(sw.match(/const PRECACHE_URLS = \[(.*?)\];/s)||[])[1]||'';
for(const asset of ["'./dictionary.js.gz'","'./shared-lexicon.js'","'./dictionary-overrides.js'"])assert.ok(precache.includes(asset),'Missing offline asset '+asset);
assert.doesNotMatch(precache,/\.apk/,'APK must not be precached');
const manifest=JSON.parse(read('manifest.webmanifest'));
assert.equal(manifest.name,'刚果金斯语翻译');
assert.equal(manifest.display,'standalone');
const apk=fs.readFileSync(path.join(root,'DWSS-Android-Installer.apk'));
const crypto=require('node:crypto');
assert.equal(crypto.createHash('sha256').update(apk).digest('hex'),'9df93884f7eafe9e3cf8ba77d61c61e7a1b050360be691d1a39e6999e3fa37f5');
console.log('PASS DWSS 0.9.100: correction replaces current shared override, confirmation/history/restore, candidate rail and withdrawn-row recovery, PWA cache, stable APK.');