#!/usr/bin/env node
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const zlib=require('node:zlib');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const read=n=>fs.readFileSync(path.join(root,n),'utf8');
const version=read('VERSION.txt'),sw=read('sw.js'),html=read('index.html'),app=read('app.js');
const boot=read('boot.js'),manifest=JSON.parse(read('manifest.webmanifest'));
assert.match(version,/^Version: 0\.9\.75$/m);
assert(sw.includes("const APP_VERSION = '0.9.75';"));
assert(sw.includes('./hanzi-pinyin.js')&&sw.includes('./pronunciation-search.js'));
assert(html.includes('content="0.9.75">'));
assert(html.includes('DWSS_AUTO_UPDATE_0_9_75'));
assert(html.includes('版本 0.9.75 · 刚果金斯语翻译'));
assert(html.includes('data-tab="pronunciation"'));
assert.equal(manifest.id,'./?app=dwss-kolwezi-swahili');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.name,'刚果金斯语翻译');
assert(app.includes("version:'0.9.75'"));
assert(app.includes("const entries=all.map(item=>({zh:item.zh"));
assert(app.includes('preferredLocalVariants(item)'));
assert(app.includes("window.addEventListener('dwss:personal-term-added',refreshPronunciationLookup)"));
assert(app.includes("window.addEventListener('dwss:personal-term-removed',refreshPronunciationLookup)"));
assert(app.includes("new CustomEvent('dwss:personal-term-removed',{detail:{id}})"));
assert(app.includes("sharedCustom=next;rebuild();renderDictionary();renderSaved();renderPronunciationLookup()"));
assert(app.includes("publicPronunciationOverrides=next;rebuild();renderDictionary();renderPublicPronunciationOverrides();renderPronunciationLookup()"));
assert(boot.indexOf('./hanzi-pinyin.js')<boot.indexOf('./pronunciation-search.js'));
assert(boot.indexOf('./pronunciation-search.js')<boot.indexOf('./app.js'));
const context={window:{}};
vm.runInNewContext(read('hanzi-pinyin.js'),context);
const pinyin=context.window.DWSS_HANZI_PINYIN;
assert(Object.keys(pinyin).length>18000);
assert.equal(pinyin['给'],'gei');assert.equal(pinyin['晓'],'xiao');assert.equal(pinyin['该'],'gai');
const searchContext={window:{DWSS_HANZI_PINYIN:pinyin}};
vm.runInNewContext(read('pronunciation-search.js'),searchContext);
const engine=searchContext.window.DWSSPronunciationSearch;
const dbContext={window:{}};
vm.runInNewContext(zlib.gunzipSync(fs.readFileSync(path.join(root,'dictionary.js.gz'))).toString(),dbContext);
const db=dbContext.window.SW_DB;
assert(db.length>=2000);
const entries=db.map(item=>({zh:item.zh,category:'内置',variants:item.variants||[]}));
assert(engine.search('给晓',entries).some(x=>x.zh==='明天'&&x.matchedReading==='该小'));
// A genuinely new user term absent from the original database is instantly searchable by the same engine.
const brandNew={zh:'测试新增词条',category:'用户新增',variants:[{reading:'该小',source:'用户手动添加',origin:'personal'}]};
assert(!entries.some(x=>x.zh===brandNew.zh));
entries.push(brandNew);
assert(engine.search('给晓',entries).some(x=>x.zh==='测试新增词条'&&x.matchedReading==='该小'));
// Multiple future additions, including an imported term, are indexed without a per-word rule.
entries.push({zh:'另一条刚新增的词',category:'用户新增',variants:[{reading:'该小',source:'备份导入',origin:'personal'}]});
assert(engine.search('给晓',entries).some(x=>x.zh==='另一条刚新增的词'));
console.log('PASS: every lookup render reads the current rebuilt full dictionary; no word-specific allowlist.');
console.log('PASS: add/update/import and delete events refresh the currently open pronunciation panel.');
console.log('PASS: terms absent from the original 2,042-entry lexicon become searchable immediately after add/import.');
console.log('PASS: exact, homophone and approximate sound matching remain shared by all new and existing terms.');
