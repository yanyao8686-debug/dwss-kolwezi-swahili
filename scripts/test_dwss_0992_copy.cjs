'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=process.env.DWSS_PUBLIC_DIR||'public';
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const version=fs.readFileSync(path.join(root,'VERSION.txt'),'utf8');
assert.match(version,/^Version: 0\.9\.92$/m);
assert.match(html,/DWSS_AUTO_UPDATE_0_9_92/);
assert.match(html,/content="0\.9\.92"/);
assert.match(html,/id="translationCorrectionPanel"/);
assert.match(html,/id="submitTranslationCorrection"/);
assert.match(html,/>提交修正<\/button>/);
assert.doesNotMatch(html,/translation-correction-help/);
assert.doesNotMatch(html,/提交修正并同步所有用户/);
assert.match(app,/已同步云端，其他用户可见。/);
assert.doesNotMatch(app,/可以直接编辑上方谐音并提交云端/);
assert.match(sw,/APP_VERSION = '0\.9\.92'/);
console.log('PASS DWSS 0.9.92 concise edit panel, live sync wording and version/cache consistency.');
